Section Pregroup.

Variable B : Type.

(* D1.  Simple types with an integer adjoint iterator: PL07 p. 316;
   L08 ch. 4 p. 8.  (a^l)^r = a is lia on Z — an honest equality. *)
Definition Simple : Type := (B * Z)%type.
Definition ladj (a : Simple) : Simple := (fst a, Z.pred (snd a)).
Definition radj (a : Simple) : Simple := (fst a, Z.succ (snd a)).

(* D2.  Compound types: the free monoid as lists (L08 ch. 4 p. 9). *)
Definition Ty : Type := list Simple.

(* D3.  Adjoints of compound types: Preller's
   (A1^(z1)...An^(zn))^l = An^(zn-1)...A1^(z1-1)  (PL07 p. 316). *)
Definition ladj_ty (p : Ty) : Ty := rev (map ladj p).
Definition radj_ty (p : Ty) : Ty := rev (map radj p).

(* D5.  Proof-relevant reductions.  The four structural steps are
   indexed by ladj a / radj a so that every yanking equation is
   cast-free (design verdict; probe-verified): L08 ch. 30 rules
   (3),(4),(6),(8),(9); CSC10 §2.2 p. 5, §3.3 p. 13. *)
Inductive Red : Ty -> Ty -> Type :=
| red_refl   (p : Ty) : Red p p
| red_trans  {p q r : Ty} : Red p q -> Red q r -> Red p r
| red_cup_l  (a : Simple) : Red [ladj a; a] []          (* a^l a <= 1 *)
| red_cup_r  (a : Simple) : Red [a; radj a] []          (* a a^r <= 1 *)
| red_cap_l  (a : Simple) : Red [] [a; ladj a]          (* 1 <= a a^l *)
| red_cap_r  (a : Simple) : Red [] [radj a; a]          (* 1 <= a^r a *)
| red_tensor {p q p' q' : Ty} : Red p p' -> Red q q' -> Red (p ++ q) (p' ++ q').

(* D4.  The order (CSC10 §2.2 p. 4): the Prop shadow of Red
   (ARTIFACT-ii). *)
Definition Le (p q : Ty) : Prop := inhabited (Red p q).

(* D6.  Casts along list equalities — needed only by the compound
   adjoint laws; deq_cast makes them semantically invisible. *)
Definition red_cast {p p' q q' : Ty} (e1 : p = p') (e2 : q = q')
  (d : Red p q) : Red p' q' :=
  match e1 in (_ = x), e2 in (_ = y) return Red x y with
  | eq_refl, eq_refl => d
  end.

(* D7.  Substitutivity, cast-free (u ++ p ++ v is right-nested):
   L08 ch. 27 p. 74 rule (7). *)
Definition red_subst (u v : Ty) {p q : Ty} (d : Red p q) :
  Red (u ++ p ++ v) (u ++ q ++ v) :=
  red_tensor (red_refl u) (red_tensor d (red_refl v)).

(* D9.  The equational theory of the free STRICT compact closed
   category on derivations — heterogeneous in the endpoints, so the
   strict monoidal laws relate derivations whose index lists are only
   propositionally equal, without transports: CSC10 §3.1 eqs (1)-(3)
   pp. 8-9, §3.3 p. 11 (the four yanking equations); PL07 (3.1). *)
Inductive deq : forall {p q p' q' : Ty}, Red p q -> Red p' q' -> Prop :=
| deq_refl {p q} (d : Red p q) : deq d d
| deq_sym {p q p' q'} (d : Red p q) (d' : Red p' q') :
    deq d d' -> deq d' d
| deq_trans {p1 q1 p2 q2 p3 q3}
    (d1 : Red p1 q1) (d2 : Red p2 q2) (d3 : Red p3 q3) :
    deq d1 d2 -> deq d2 d3 -> deq d1 d3
| deq_cong_trans {p q r p' q' r'}
    (d1 : Red p q) (d2 : Red q r) (d1' : Red p' q') (d2' : Red q' r') :
    deq d1 d1' -> deq d2 d2' ->
    deq (red_trans d1 d2) (red_trans d1' d2')
| deq_cong_tensor {p1 q1 p2 q2 p1' q1' p2' q2'}
    (d1 : Red p1 q1) (d2 : Red p2 q2)
    (d1' : Red p1' q1') (d2' : Red p2' q2') :
    deq d1 d1' -> deq d2 d2' ->
    deq (red_tensor d1 d2) (red_tensor d1' d2')
| deq_assoc {p q r t} (d1 : Red p q) (d2 : Red q r) (d3 : Red r t) :
    deq (red_trans (red_trans d1 d2) d3) (red_trans d1 (red_trans d2 d3))
| deq_unit_l {p q} (d : Red p q) : deq (red_trans (red_refl p) d) d
| deq_unit_r {p q} (d : Red p q) : deq (red_trans d (red_refl q)) d
| deq_tensor_assoc {p1 q1 p2 q2 p3 q3}
    (d1 : Red p1 q1) (d2 : Red p2 q2) (d3 : Red p3 q3) :
    deq (red_tensor (red_tensor d1 d2) d3)
        (red_tensor d1 (red_tensor d2 d3))
| deq_tensor_unit_l {p q} (d : Red p q) :
    deq (red_tensor (red_refl []) d) d
| deq_tensor_unit_r {p q} (d : Red p q) :
    deq (red_tensor d (red_refl [])) d
| deq_tensor_refl (p q : Ty) :
    deq (red_tensor (red_refl p) (red_refl q)) (red_refl (p ++ q))
| deq_interchange {p1 q1 r1 p2 q2 r2}
    (f1 : Red p1 q1) (g1 : Red q1 r1) (f2 : Red p2 q2) (g2 : Red q2 r2) :
    deq (red_trans (red_tensor f1 f2) (red_tensor g1 g2))
        (red_tensor (red_trans f1 g1) (red_trans f2 g2))
| deq_cast {p q p' q'} (e1 : p = p') (e2 : q = q') (d : Red p q) :
    deq (red_cast e1 e2 d) d
| deq_snake_1 (a : Simple) :
    deq (red_trans (red_tensor (red_cap_l a) (red_refl [a]))
                   (red_tensor (red_refl [a]) (red_cup_l a)))
        (red_refl [a])
| deq_snake_2 (a : Simple) :
    deq (red_trans (red_tensor (red_refl [a]) (red_cap_r a))
                   (red_tensor (red_cup_r a) (red_refl [a])))
        (red_refl [a])
| deq_snake_3 (a : Simple) :
    deq (red_trans (red_tensor (red_refl [ladj a]) (red_cap_l a))
                   (red_tensor (red_cup_l a) (red_refl [ladj a])))
        (red_refl [ladj a])
| deq_snake_4 (a : Simple) :
    deq (red_trans (red_tensor (red_cap_r a) (red_refl [radj a]))
                   (red_tensor (red_refl [radj a]) (red_cup_r a)))
        (red_refl [radj a]).


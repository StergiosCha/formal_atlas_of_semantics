Section Meaning.

Variable B : Type.
Variable dim : B -> nat.

(* D20.  F on objects: the iterator is ignored — F(x^l) = F(x) is
   DEFINITIONAL (ARTIFACT-ii). *)
Definition dimS (a : Simple B) : nat := dim (fst a).
Definition dimT (p : Ty B) : nat :=
  fold_right (fun a d => (dimS a * d)%nat) 1%nat p.

(* D21.  F on reductions, by structural recursion (probe-verified: no
   return annotation needed thanks to the phantom dims). *)
Fixpoint F {p q : Ty B} (d : Red p q) : nat -> nat -> Q :=
  match d with
  | red_refl _ => idm
  | @red_trans _ _ q0 _ d1 d2 => mmul (dimT q0) (F d2) (F d1)
  | red_cup_l a => eps (dimS a)
  | red_cup_r a => eps (dimS a)
  | red_cap_l a => eta (dimS a)
  | red_cap_r a => eta (dimS a)
  | @red_tensor _ _ q0 _ q0' d1 d2 =>
      kron (dimT q0') (dimT q0) (F d1) (F d2)
  end.

(* D22.  Tensoring the word vectors (right fold aligned with dimT and
   right-nested red_tensor; the kron row-dim is the FULL tail dim —
   pitfall 3). *)
Fixpoint tensor_words (ws : list (Ty B * (nat -> nat -> Q))) :
  nat -> nat -> Q :=
  match ws with
  | [] => fun _ _ => 1
  | (t, v) :: rest =>
      kron (dimT (concat (map fst rest))) 1%nat v (tensor_words rest)
  end.

Definition meaning {p q : Ty B} (d : Red p q)
  (ws : list (Ty B * (nat -> nat -> Q))) : nat -> nat -> Q :=
  mmul (dimT p) (F d) (tensor_words ws).

(* T25.  F is strictly monoidal on objects. *)
Theorem dimT_app : forall p q, dimT (p ++ q) = (dimT p * dimT q)%nat.
Proof.
  induction p as [| a p IH]; intros q; simpl.
  - lia.
  - rewrite IH; apply Nat.mul_assoc.
Qed.

Theorem dimT_ladj : forall p, dimT (ladj_ty p) = dimT p.
Proof.
  induction p as [| a p IH]; simpl; [reflexivity |].
  unfold ladj_ty in *; simpl.
  rewrite dimT_app, IH; simpl.
  rewrite Nat.mul_1_r; apply Nat.mul_comm.
Qed.

Theorem dimT_radj : forall p, dimT (radj_ty p) = dimT p.
Proof.
  induction p as [| a p IH]; simpl; [reflexivity |].
  unfold radj_ty in *; simpl.
  rewrite dimT_app, IH; simpl.
  rewrite Nat.mul_1_r; apply Nat.mul_comm.
Qed.

(* T26.  Functoriality equations — definitional, stated so the brief's
   "functoriality" has an explicit honest form. *)
Theorem F_refl : forall p, F (red_refl p) = idm.
Proof. reflexivity. Qed.

Theorem F_trans : forall p q r (d1 : Red p q) (d2 : Red q r),
  F (red_trans d1 d2) = mmul (dimT q) (F d2) (F d1).
Proof. reflexivity. Qed.

Theorem F_tensor : forall p q p' q' (d1 : Red p p') (d2 : Red q q'),
  F (red_tensor d1 d2) = kron (dimT q') (dimT q) (F d1) (F d2).
Proof. reflexivity. Qed.

Theorem F_cup_l : forall a, F (red_cup_l a) = eps (dimS a).
Proof. reflexivity. Qed.

Theorem F_cap_r : forall a, F (red_cap_r a) = eta (dimS a).
Proof. reflexivity. Qed.

(* T27.  Casts are invisible to the semantics. *)
Theorem F_cast : forall p p' q q' (e1 : p = p') (e2 : q = q')
  (d : Red p q), F (red_cast e1 e2 d) = F d.
Proof. intros p p' q q' e1 e2 d; destruct e1, e2; reflexivity. Qed.

End Meaning.


(* T18.  Category laws (CSC10 §3.1 p. 8). *)
Lemma mmul_idm_l : forall m n A,
  mat_eq m n (mmul m idm A) A.
Proof.
  intros m n A i j Hi Hj; unfold mmul, idm.
  rewrite (qsum_ext m _ (fun l => if Nat.eqb l i then A l j else 0)).
  - exact (qsum_delta_l m (fun l => A l j) i Hi).
  - intros l _.
    rewrite (Nat.eqb_sym i l).
    destruct (Nat.eqb l i); ring.
Qed.

Lemma mmul_idm_r : forall m n A,
  mat_eq m n (mmul n A idm) A.
Proof.
  intros m n A i j Hi Hj; unfold mmul, idm.
  rewrite (qsum_ext n _ (fun l => if Nat.eqb l j then A i l else 0)).
  - exact (qsum_delta_l n (fun l => A i l) j Hj).
  - intros l _.
    destruct (Nat.eqb l j); ring.
Qed.

Lemma mmul_assoc : forall m k l n A B C,
  mat_eq m n (mmul l (mmul k A B) C) (mmul k A (mmul l B C)).
Proof.
  intros m k l n A B C i j Hi Hj; unfold mmul.
  rewrite (qsum_ext l _
    (fun c => qsum k (fun b => A i b * B b c * C c j))).
  2:{ intros c _.
      rewrite <- (qsum_scale_r k (C c j) (fun b => A i b * B b c)).
      apply qsum_ext; intros b _; ring. }
  rewrite qsum_swap.
  apply qsum_ext; intros b _.
  rewrite <- (qsum_scale_l l (A i b) (fun c => B b c * C c j)).
  apply qsum_ext; intros c _; ring.
Qed.

(* T19.  Bifunctoriality / interchange (CSC10 eq. (3) p. 9). *)
Lemma interchange : forall m1 k1 n1 m2 k2 n2 G1 F1 G2 F2,
  mat_eq (m1 * m2) (n1 * n2)
    (mmul (k1 * k2) (kron m2 k2 G1 G2) (kron k2 n2 F1 F2))
    (kron m2 n2 (mmul k1 G1 F1) (mmul k2 G2 F2)).
Proof.
  intros m1 k1 n1 m2 k2 n2 G1 F1 G2 F2 i j Hi Hj.
  unfold mmul, kron.
  rewrite qsum_split.
  rewrite (qsum_ext k1 _
    (fun a => qsum k2 (fun b =>
       (G1 (i / m2)%nat a * F1 a (j / n2)%nat) *
       (G2 (i mod m2)%nat b * F2 b (j mod n2)%nat)))).
  - rewrite <- qsum_mul; reflexivity.
  - intros a Ha; apply qsum_ext; intros b Hb.
    rewrite (div_add_small a b k2 Hb), (mod_add_small a b k2 Hb); ring.
Qed.

Lemma kron_idm : forall m n,
  mat_eq (m * n) (m * n) (kron n n idm idm) idm.
Proof.
  intros m n i j Hi Hj; unfold kron, idm.
  destruct (Nat.eqb i j) eqn:E.
  - apply Nat.eqb_eq in E; subst j.
    rewrite Nat.eqb_refl, Nat.eqb_refl; ring.
  - apply Nat.eqb_neq in E.
    destruct (Nat.eqb (i / n) (j / n)) eqn:E1;
      destruct (Nat.eqb (i mod n) (j mod n)) eqn:E2; try ring.
    apply Nat.eqb_eq in E1; apply Nat.eqb_eq in E2.
    exfalso; apply E.
    rewrite (div_mod_split i n), (div_mod_split j n), E1, E2; reflexivity.
Qed.

(* T20.  STRICT monoidal laws on the nose — the load-bearing lemmas
   that let F and tensor_words bracket tensors differently
   (CSC10 §3.1 eqs (1)-(2)). *)
Lemma kron_assoc : forall m1 n1 m2 n2 m3 n3 A B C,
  mat_eq (m1 * m2 * m3) (n1 * n2 * n3)
    (kron m3 n3 (kron m2 n2 A B) C)
    (kron (m2 * m3) (n2 * n3) A (kron m3 n3 B C)).
Proof.
  intros m1 n1 m2 n2 m3 n3 A B C i j Hi Hj; unfold kron.
  destruct m3 as [| m3']; [lia |].
  destruct n3 as [| n3']; [lia |].
  destruct m2 as [| m2']; [lia |].
  destruct n2 as [| n2']; [lia |].
  set (m3 := S m3') in *; set (n3 := S n3') in *.
  set (m2 := S m2') in *; set (n2 := S n2') in *.
  rewrite (Nat.mul_comm m2 m3), (Nat.mul_comm n2 n3).
  rewrite (Nat.Div0.div_div i m3 m2), (Nat.Div0.div_div j n3 n2).
  rewrite (Nat.Div0.mod_mul_r i m3 m2), (Nat.Div0.mod_mul_r j n3 n2).
  assert (Him : ((i mod m3 + m3 * ((i / m3) mod m2)) / m3)%nat
                = ((i / m3) mod m2)%nat).
  { rewrite Nat.add_comm, <- (Nat.mul_comm ((i / m3) mod m2) m3).
    apply div_add_small.
    apply Nat.mod_upper_bound; unfold m3; lia. }
  assert (Him2 : ((i mod m3 + m3 * ((i / m3) mod m2)) mod m3)%nat
                 = (i mod m3)%nat).
  { rewrite Nat.add_comm, <- (Nat.mul_comm ((i / m3) mod m2) m3).
    apply mod_add_small.
    apply Nat.mod_upper_bound; unfold m3; lia. }
  assert (Hjn : ((j mod n3 + n3 * ((j / n3) mod n2)) / n3)%nat
                = ((j / n3) mod n2)%nat).
  { rewrite Nat.add_comm, <- (Nat.mul_comm ((j / n3) mod n2) n3).
    apply div_add_small.
    apply Nat.mod_upper_bound; unfold n3; lia. }
  assert (Hjn2 : ((j mod n3 + n3 * ((j / n3) mod n2)) mod n3)%nat
                 = (j mod n3)%nat).
  { rewrite Nat.add_comm, <- (Nat.mul_comm ((j / n3) mod n2) n3).
    apply mod_add_small.
    apply Nat.mod_upper_bound; unfold n3; lia. }
  rewrite Him, Him2, Hjn, Hjn2; ring.
Qed.

Lemma kron_unit_l : forall m n A,
  mat_eq m n (kron m n idm A) A.
Proof.
  intros m n A i j Hi Hj; unfold kron, idm.
  rewrite (Nat.div_small i m Hi), (Nat.div_small j n Hj); simpl.
  rewrite (Nat.mod_small i m Hi), (Nat.mod_small j n Hj); ring.
Qed.

Lemma kron_unit_r : forall m n A,
  mat_eq m n (kron 1 1 A idm) A.
Proof.
  intros m n A i j Hi Hj; unfold kron, idm.
  rewrite Nat.div_1_r, Nat.div_1_r, Nat.mod_1_r, Nat.mod_1_r; simpl; ring.
Qed.


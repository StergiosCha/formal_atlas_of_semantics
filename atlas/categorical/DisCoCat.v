Theorem Le_refl : forall p, Le p p.
Proof. intros p; exact (inhabits (red_refl p)). Qed.

Theorem Le_trans : forall p q r, Le p q -> Le q r -> Le p r.
Proof.
  intros p q r [d1] [d2]; exact (inhabits (red_trans d1 d2)).
Qed.

Theorem Le_tensor : forall p q p' q',
  Le p p' -> Le q q' -> Le (p ++ q) (p' ++ q').
Proof.
  intros p q p' q' [d1] [d2]; exact (inhabits (red_tensor d1 d2)).
Qed.

Theorem Le_subst : forall u v p q,
  Le p q -> Le (u ++ p ++ v) (u ++ q ++ v).
Proof.
  intros u v p q [d]; exact (inhabits (red_subst u v d)).
Qed.

(* T3.  Adjoint laws for simple types, including iterated adjoints:
   CSC10 p. 5; L08 ch. 30. *)
Theorem Le_cup_l : forall a, Le [ladj a; a] [].
Proof. intros a; exact (inhabits (red_cup_l a)). Qed.

Theorem Le_cup_r : forall a, Le [a; radj a] [].
Proof. intros a; exact (inhabits (red_cup_r a)). Qed.

Theorem Le_cap_l : forall a, Le [] [a; ladj a].
Proof. intros a; exact (inhabits (red_cap_l a)). Qed.

Theorem Le_cap_r : forall a, Le [] [radj a; a].
Proof. intros a; exact (inhabits (red_cap_r a)). Qed.

Theorem Le_cup_ll : forall a, Le [ladj (ladj a); ladj a] [].
Proof. intros a; exact (inhabits (red_cup_l (ladj a))). Qed.

Theorem Le_cap_rr : forall a, Le [] [radj (radj a); radj a].
Proof. intros a; exact (inhabits (red_cap_r (radj a))). Qed.

(* T5.  Opposite adjoints annihilate — honest equalities of types:
   L08 (13), ch. 27 (4); CSC10 p. 5; PL07 p. 316. *)
Theorem radj_ladj : forall a, radj (ladj a) = a.
Proof.
  intros [b z]; unfold radj, ladj; simpl; f_equal; lia.
Qed.

Theorem ladj_radj : forall a, ladj (radj a) = a.
Proof.
  intros [b z]; unfold radj, ladj; simpl; f_equal; lia.
Qed.

Theorem radj_ty_ladj_ty : forall p, radj_ty (ladj_ty p) = p.
Proof.
  intros p; unfold radj_ty, ladj_ty.
  rewrite map_rev, rev_involutive, map_map.
  rewrite (map_ext _ id) by (intros a; apply radj_ladj).
  apply map_id.
Qed.

Theorem ladj_ty_radj_ty : forall p, ladj_ty (radj_ty p) = p.
Proof.
  intros p; unfold radj_ty, ladj_ty.
  rewrite map_rev, rev_involutive, map_map.
  rewrite (map_ext _ id) by (intros a; apply ladj_radj).
  apply map_id.
Qed.

(* T6.  The compound adjoint is an anti-homomorphism:
   L08 (11),(12); CSC10 p. 5. *)
Theorem ladj_ty_app : forall p q,
  ladj_ty (p ++ q) = ladj_ty q ++ ladj_ty p.
Proof.
  intros p q; unfold ladj_ty; rewrite map_app, rev_app_distr; reflexivity.
Qed.

Theorem radj_ty_app : forall p q,
  radj_ty (p ++ q) = radj_ty q ++ radj_ty p.
Proof.
  intros p q; unfold radj_ty; rewrite map_app, rev_app_distr; reflexivity.
Qed.

Theorem ladj_ty_nil : ladj_ty [] = [].
Proof. reflexivity. Qed.

Theorem radj_ty_nil : radj_ty [] = [].
Proof. reflexivity. Qed.

(* T9.  Fidelity: Le is a PREORDER, not a partial order — a and
   a a^r a reduce to each other but differ as strings; the free
   pregroup is the quotient we deliberately do not form (ARTIFACT-v):
   L08 ch. 30 (5); PL07 p. 310. *)
Theorem le_not_antisymmetric : forall a,
  Le [a] [a; radj a; a] /\ Le [a; radj a; a] [a] /\
  [a] <> [a; radj a; a].
Proof.
  intros a; refine (conj _ (conj _ _)).
  - exact (inhabits (red_tensor (red_refl [a]) (red_cap_r a))).
  - exact (inhabits (red_tensor (red_cup_r a) (red_refl [a]))).
  - intros H; inversion H.
Qed.

(* T11.  deq only relates derivations with (propositionally) equal
   endpoints. *)
Theorem deq_endpoints : forall p q p' q' (d : Red p q) (d' : Red p' q'),
  deq d d' -> p = p' /\ q = q'.
Proof.
  intros p q p' q' d d' H; induction H;
    repeat match goal with
    | IH : _ /\ _ |- _ => destruct IH
    end; subst; try (split; reflexivity).
  - (* tensor_assoc *) split; symmetry; apply app_assoc.
  - (* tensor_unit_r *) split; apply app_nil_r.
Qed.


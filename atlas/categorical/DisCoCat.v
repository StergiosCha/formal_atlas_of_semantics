(* Digit decomposition of an index below d*(d*d). *)
Lemma three_digits : forall d l,
  (0 < d)%nat -> (l < d * (d * d))%nat ->
  ((l / (d * d)) < d)%nat /\
  (((l mod (d * d)) / d) < d)%nat /\
  (((l mod (d * d)) mod d) < d)%nat /\
  l = ((l / (d * d)) * (d * d) +
       (((l mod (d * d)) / d) * d + (l mod (d * d)) mod d))%nat /\
  (l / d)%nat = ((l / (d * d)) * d + (l mod (d * d)) / d)%nat /\
  (l mod d)%nat = ((l mod (d * d)) mod d)%nat.
Proof.
  intros d l Hd Hl.
  set (a := (l / (d * d))%nat).
  set (r := (l mod (d * d))%nat).
  set (b := (r / d)%nat).
  set (c := (r mod d)%nat).
  assert (Ha : (a < d)%nat) by (apply div_lt; exact Hl).
  assert (Hr : (r < d * d)%nat) by (apply mod_lt with (m := d); exact Hl).
  assert (Hb : (b < d)%nat) by (apply div_lt; exact Hr).
  assert (Hc : (c < d)%nat) by (apply mod_lt with (m := d); exact Hr).
  assert (Hlr : l = (a * (d * d) + r)%nat) by (apply div_mod_split).
  assert (Hrbc : r = (b * d + c)%nat) by (apply div_mod_split).
  assert (Hflat : l = ((a * d + b) * d + c)%nat).
  { rewrite Hlr, Hrbc; ring. }
  repeat split; try assumption.
  - lia.
  - rewrite Hflat; apply div_add_small; exact Hc.
  - rewrite Hflat; apply mod_add_small; exact Hc.
Qed.

(* T21.  The snake (yanking) equations, at every dimension (CSC10 §3.3
   p. 11).  With V^l = V^r = V there are two computational shapes; the
   four named equations of the calculus map onto them (see F_deq). *)
Lemma snake_A : forall d,
  mat_eq d d
    (mmul (d * (d * d))
       (kron 1 (d * d) idm (eps d))
       (kron d d (eta d) idm))
    idm.
Proof.
  intros d i j Hi Hj.
  assert (Hd : (0 < d)%nat) by lia.
  unfold mmul.
  rewrite (qsum_ext (d * (d * d)) _
    (fun l => if Nat.eqb l (i * (d * d) + (i * d + i)) then
                (if Nat.eqb i j then 1 else 0) else 0)).
  { apply (qsum_delta_l (d * (d * d))
            (fun _ => if Nat.eqb i j then 1 else 0)
            (i * (d * d) + (i * d + i))%nat); nia. }
  intros l Hl.
  destruct (three_digits d l Hd Hl) as
    [Ha [Hb [Hc [Hdec [Hld Hlm]]]]].
  set (a := (l / (d * d))%nat) in *.
  set (b := ((l mod (d * d)) / d)%nat) in *.
  set (c := ((l mod (d * d)) mod d)%nat) in *.
  unfold kron, idm, eps, eta.
  rewrite Nat.div_1_r.
  rewrite Hld, (div_add_small a b d Hb), (mod_add_small a b d Hb).
  rewrite Hlm.
  rewrite (Nat.mod_small j d Hj).
  fold a b c.
  destruct (Nat.eqb l (i * (d * d) + (i * d + i))) eqn:El.
  - apply Nat.eqb_eq in El.
    assert (Hai : a = i).
    { unfold a; rewrite El; apply div_add_small; nia. }
    assert (Hri : (l mod (d * d))%nat = (i * d + i)%nat).
    { rewrite El; apply mod_add_small; nia. }
    assert (Hbi : b = i).
    { unfold b; rewrite Hri; apply div_add_small; lia. }
    assert (Hci : c = i).
    { unfold c; rewrite Hri; apply mod_add_small; lia. }
    rewrite Hai, Hbi, Hci, !Nat.eqb_refl.
    destruct (Nat.eqb i j); ring.
  - apply Nat.eqb_neq in El.
    destruct (Nat.eqb i a) eqn:E1;
    destruct (Nat.eqb b c) eqn:E2;
    destruct (Nat.eqb a b) eqn:E3;
    destruct (Nat.eqb c j) eqn:E4; try ring.
    apply Nat.eqb_eq in E1; apply Nat.eqb_eq in E2;
    apply Nat.eqb_eq in E3; apply Nat.eqb_eq in E4.
    exfalso; apply El.
    assert (Hai : a = i) by lia.
    assert (Hbi : b = i) by lia.
    assert (Hci : c = i) by lia.
    rewrite Hdec, Hai, Hbi, Hci; reflexivity.
Qed.

Lemma snake_B : forall d,
  mat_eq d d
    (mmul (d * (d * d))
       (kron d d (eps d) idm)
       (kron (d * d) 1 idm (eta d)))
    idm.
Proof.
  intros d i j Hi Hj.
  assert (Hd : (0 < d)%nat) by lia.
  unfold mmul.
  rewrite (qsum_ext (d * (d * d)) _
    (fun l => if Nat.eqb l (j * (d * d) + (j * d + j)) then
                (if Nat.eqb i j then 1 else 0) else 0)).
  { apply (qsum_delta_l (d * (d * d))
            (fun _ => if Nat.eqb i j then 1 else 0)
            (j * (d * d) + (j * d + j))%nat); nia. }
  intros l Hl.
  destruct (three_digits d l Hd Hl) as
    [Ha [Hb [Hc [Hdec [Hld Hlm]]]]].
  set (a := (l / (d * d))%nat) in *.
  set (b := ((l mod (d * d)) / d)%nat) in *.
  set (c := ((l mod (d * d)) mod d)%nat) in *.
  unfold kron, idm, eps, eta.
  rewrite Nat.div_1_r.
  rewrite Hld, (div_add_small a b d Hb), (mod_add_small a b d Hb).
  rewrite Hlm.
  rewrite (Nat.mod_small i d Hi).
  fold a b c.
  destruct (Nat.eqb l (j * (d * d) + (j * d + j))) eqn:El.
  - apply Nat.eqb_eq in El.
    assert (Haj : a = j).
    { unfold a; rewrite El; apply div_add_small; nia. }
    assert (Hrj : (l mod (d * d))%nat = (j * d + j)%nat).
    { rewrite El; apply mod_add_small; nia. }
    assert (Hbj : b = j).
    { unfold b; rewrite Hrj; apply div_add_small; lia. }
    assert (Hcj : c = j).
    { unfold c; rewrite Hrj; apply mod_add_small; lia. }
    rewrite Haj, Hbj, Hcj, !Nat.eqb_refl.
    destruct (Nat.eqb i j); ring.
  - apply Nat.eqb_neq in El.
    destruct (Nat.eqb a b) eqn:E1;
    destruct (Nat.eqb i c) eqn:E2;
    destruct (Nat.eqb a j) eqn:E3;
    destruct (Nat.eqb b c) eqn:E4; try ring.
    apply Nat.eqb_eq in E1; apply Nat.eqb_eq in E2;
    apply Nat.eqb_eq in E3; apply Nat.eqb_eq in E4.
    exfalso; apply El.
    assert (Haj : a = j) by lia.
    assert (Hbj : b = j) by lia.
    assert (Hcj : c = j) by lia.
    rewrite Hdec, Haj, Hbj, Hcj; reflexivity.
Qed.

(* T22.  eps is the inner product (CSC10 eq. (5) p. 13). *)
Lemma eps_general : forall d (c : nat -> nat -> Q),
  mmul (d * d) (eps d) c 0%nat 0%nat ==
  qsum d (fun i => c (i * d + i)%nat 0%nat).
Proof.
  intros d c; unfold mmul.
  rewrite qsum_split.
  rewrite (qsum_ext d _
    (fun a => qsum d (fun b =>
       if Nat.eqb a b then c (a * d + b)%nat 0%nat else 0))).
  - apply qsum_ext; intros a Ha.
    rewrite (qsum_delta_r d (fun b => c (a * d + b)%nat 0%nat) a Ha).
    reflexivity.
  - intros a Ha; apply qsum_ext; intros b Hb.
    unfold eps.
    rewrite (div_add_small a b d Hb), (mod_add_small a b d Hb).
    destruct (Nat.eqb a b); ring.
Qed.

Lemma eps_inner : forall d v w,
  mmul (d * d) (eps d) (kron d 1 v w) 0%nat 0%nat == inner d v w.
Proof.
  intros d v w; rewrite eps_general; unfold inner.
  apply qsum_ext; intros i Hi.
  unfold kron.
  rewrite (div_add_small i i d Hi), (mod_add_small i i d Hi).
  reflexivity.
Qed.

(* T23.  The trace: eps . eta = the dimension, as a scalar
   (CSC10 p. 12). *)
Lemma qsum_const1 : forall n,
  qsum n (fun _ => 1) == inject_Z (Z.of_nat n).
Proof.
  induction n as [| m IH]; [reflexivity |].
  change (qsum (S m) (fun _ => 1)) with (qsum m (fun _ => 1) + 1).
  rewrite IH, Nat2Z.inj_succ, <- Z.add_1_l, inject_Z_plus; ring.
Qed.

Lemma trace_eps_eta : forall d,
  mmul (d * d) (eps d) (eta d) 0%nat 0%nat == inject_Z (Z.of_nat d).
Proof.
  intros d; rewrite eps_general.
  rewrite (qsum_ext d _ (fun _ => 1)).
  - apply qsum_const1.
  - intros i Hi; unfold eta.
    rewrite (div_add_small i i d Hi), (mod_add_small i i d Hi).
    rewrite Nat.eqb_refl; reflexivity.
Qed.


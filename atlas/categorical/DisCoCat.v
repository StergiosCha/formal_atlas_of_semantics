Lemma qsum_ext : forall n f g,
  (forall i, (i < n)%nat -> f i == g i) -> qsum n f == qsum n g.
Proof.
  induction n as [| m IH]; intros f g H; simpl; [reflexivity |].
  rewrite (IH f g (fun i Hi => H i (Nat.lt_lt_succ_r _ _ Hi))).
  rewrite (H m (Nat.lt_succ_diag_r m)); reflexivity.
Qed.

Lemma qsum_plus : forall n f g,
  qsum n (fun i => f i + g i) == qsum n f + qsum n g.
Proof.
  induction n as [| m IH]; intros f g; simpl; [ring |].
  rewrite IH; ring.
Qed.

Lemma qsum_scale_l : forall n c f,
  qsum n (fun i => c * f i) == c * qsum n f.
Proof.
  induction n as [| m IH]; intros c f; simpl; [ring |].
  rewrite IH; ring.
Qed.

Lemma qsum_scale_r : forall n c f,
  qsum n (fun i => f i * c) == qsum n f * c.
Proof.
  induction n as [| m IH]; intros c f; simpl; [ring |].
  rewrite IH; ring.
Qed.

Lemma qsum_zero : forall n f,
  (forall i, (i < n)%nat -> f i == 0) -> qsum n f == 0.
Proof.
  induction n as [| m IH]; intros f H; simpl; [reflexivity |].
  rewrite (IH f (fun i Hi => H i (Nat.lt_lt_succ_r _ _ Hi))).
  rewrite (H m (Nat.lt_succ_diag_r m)); ring.
Qed.

Lemma qsum_app : forall a b f,
  qsum (a + b) f == qsum a f + qsum b (fun i => f (a + i)%nat).
Proof.
  intros a b; induction b as [| b IH]; intros f.
  - rewrite Nat.add_0_r; simpl; ring.
  - rewrite Nat.add_succ_r; simpl.
    rewrite IH; ring.
Qed.

Lemma qsum_swap : forall m n f,
  qsum m (fun i => qsum n (fun j => f i j)) ==
  qsum n (fun j => qsum m (fun i => f i j)).
Proof.
  induction m as [| m IH]; intros n f; simpl.
  - rewrite (qsum_zero n (fun _ => 0)); [reflexivity | intros; reflexivity].
  - rewrite (IH n f), <- qsum_plus.
    apply qsum_ext; intros j _; reflexivity.
Qed.

Lemma qsum_mul : forall m n f g,
  qsum m f * qsum n g ==
  qsum m (fun a => qsum n (fun b => f a * g b)).
Proof.
  induction m as [| m IH]; intros n f g; simpl; [ring |].
  rewrite <- IH.
  rewrite (qsum_scale_l n (f m) g); ring.
Qed.

Lemma qsum_delta_l : forall n (a : nat -> Q) j,
  (j < n)%nat ->
  qsum n (fun k => if Nat.eqb k j then a k else 0) == a j.
Proof.
  induction n as [| m IH]; intros a j Hj; [lia | simpl].
  destruct (Nat.eqb m j) eqn:E.
  - apply Nat.eqb_eq in E; subst j.
    rewrite (qsum_zero m).
    + ring.
    + intros i Hi.
      destruct (Nat.eqb i m) eqn:Ei; [apply Nat.eqb_eq in Ei; lia | reflexivity].
  - apply Nat.eqb_neq in E.
    rewrite (IH a j) by lia; ring.
Qed.

Lemma qsum_delta_r : forall n (a : nat -> Q) j,
  (j < n)%nat ->
  qsum n (fun k => if Nat.eqb j k then a k else 0) == a j.
Proof.
  intros n a j Hj.
  rewrite (qsum_ext n _ (fun k => if Nat.eqb k j then a k else 0)).
  - apply qsum_delta_l; exact Hj.
  - intros i _; rewrite Nat.eqb_sym; reflexivity.
Qed.

Lemma qsum_split : forall m n f,
  qsum (m * n) f ==
  qsum m (fun a => qsum n (fun b => f (a * n + b)%nat)).
Proof.
  induction m as [| m IH]; intros n f; simpl; [reflexivity |].
  replace (n + m * n)%nat with (m * n + n)%nat by lia.
  rewrite qsum_app, (IH n f).
  apply Qplus_comp; [apply qsum_ext; intros a _; reflexivity |].
  apply qsum_ext; intros b _.
  replace (m * n + b)%nat with (m * n + b)%nat by lia; reflexivity.
Qed.


(* T17.  Congruence of the operations w.r.t. mat_eq. *)
Lemma mmul_ext : forall m k n A A' B B',
  mat_eq m k A A' -> mat_eq k n B B' ->
  mat_eq m n (mmul k A B) (mmul k A' B').
Proof.
  intros m k n A A' B B' HA HB i j Hi Hj; unfold mmul.
  apply qsum_ext; intros l Hl.
  rewrite (HA i l Hi Hl), (HB l j Hl Hj); reflexivity.

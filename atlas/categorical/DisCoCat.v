Section Soundness.

Variable B : Type.
Variable dim : B -> nat.

(* T28.  The substantive theorem: derivations equal in the free strict
   compact closed category have equal matrices — well-definedness of the
   meaning map relative to the calculus, for ALL reductions (CSC10 §3.1
   p. 9, sound direction of coherence; PL07 Prop. 1). *)
Theorem F_deq : forall (p q p' q' : Ty B) (d : Red p q) (d' : Red p' q'),
  deq d d' ->
  p = p' /\ q = q' /\
  mat_eq (dimT dim q) (dimT dim p) (F dim d) (F dim d').
Proof.
  intros p q p' q' d d' H; induction H.
  - (* refl *)
    split; [reflexivity | split; [reflexivity | apply mat_eq_refl]].
  - (* sym *)
    repeat match goal with IH : _ /\ _ |- _ => destruct IH end; subst.
    split; [reflexivity | split; [reflexivity |]].
    apply mat_eq_sym; assumption.
  - (* trans *)
    repeat match goal with IH : _ /\ _ |- _ => destruct IH end; subst.
    split; [reflexivity | split; [reflexivity |]].
    eapply mat_eq_trans; eassumption.
  - (* cong_trans *)
    repeat match goal with IH : _ /\ _ |- _ => destruct IH end; subst.
    split; [reflexivity | split; [reflexivity |]].
    simpl; apply mmul_ext; assumption.
  - (* cong_tensor *)
    repeat match goal with IH : _ /\ _ |- _ => destruct IH end; subst.
    split; [reflexivity | split; [reflexivity |]].
    rewrite !(dimT_app B dim); simpl; apply kron_ext; assumption.
  - (* assoc *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; apply mat_eq_sym, mmul_assoc.
  - (* unit_l *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; apply mmul_idm_r.
  - (* unit_r *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; apply mmul_idm_l.
  - (* tensor_assoc *)
    split; [symmetry; apply app_assoc |
            split; [symmetry; apply app_assoc |]].
    rewrite !(dimT_app B dim); simpl.
    rewrite !(dimT_app B dim).
    apply kron_assoc.
  - (* tensor_unit_l *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; apply kron_unit_l.
  - (* tensor_unit_r *)
    split; [apply app_nil_r | split; [apply app_nil_r |]].
    apply (mat_eq_dims (dimT dim q) _ (dimT dim p) _);
      [rewrite app_nil_r; reflexivity |
       rewrite app_nil_r; reflexivity |].
    simpl; apply kron_unit_r.
  - (* tensor_refl *)
    split; [reflexivity | split; [reflexivity |]].
    rewrite !(dimT_app B dim); simpl; apply kron_idm.
  - (* interchange *)
    split; [reflexivity | split; [reflexivity |]].
    rewrite !(dimT_app B dim); simpl.
    rewrite !(dimT_app B dim).
    apply interchange.
  - (* cast *)
    match goal with
    | E1 : _ = _, E2 : _ = _ |- _ => destruct E1, E2
    end.
    split; [reflexivity | split; [reflexivity | apply mat_eq_refl]].
  - (* snake_1 *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; rewrite !Nat.mul_1_r; apply snake_A.
  - (* snake_2 *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; rewrite !Nat.mul_1_r; apply snake_B.
  - (* snake_3 *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; rewrite !Nat.mul_1_r; apply snake_B.
  - (* snake_4 *)
    split; [reflexivity | split; [reflexivity |]].
    simpl; rewrite !Nat.mul_1_r; apply snake_A.
Qed.

(* T30.  Meanings are invariant under deq — the brief's
   well-definedness statement at sentence level (CSC10 Def 3.2;
   CGS13 Def 4.2). *)
Theorem meaning_deq : forall (p q p' q' : Ty B)
  (d : Red p q) (d' : Red p' q') ws,
  deq d d' ->
  mat_eq (dimT dim q) 1 (meaning dim d ws) (meaning dim d' ws).
Proof.
  intros p q p' q' d d' ws H.
  destruct (F_deq p q p' q' d d' H) as [E1 [E2 M]]; subst.
  unfold meaning; apply mmul_ext; [exact M | apply mat_eq_refl].
Qed.

End Soundness.

(* T29.  Corollary at the example grammar: all readings of "John likes
   Mary" have the same matrix, for EVERY dimension assignment
   (T12 + T28); the fixed-dim reflection is
   ExModel.readings_agree_computationally. *)
Theorem F_tv_orders : forall (dim : Examples.basic -> nat),
  mat_eq (dimT dim [Examples.s])
         (dimT dim [Examples.n; radj Examples.n; Examples.s;
                    ladj Examples.n; Examples.n])
         (F dim Examples.tv_red_subj) (F dim Examples.tv_red) /\
  mat_eq (dimT dim [Examples.s])
         (dimT dim [Examples.n; radj Examples.n; Examples.s;
                    ladj Examples.n; Examples.n])
         (F dim Examples.tv_red_obj) (F dim Examples.tv_red) /\
  mat_eq (dimT dim [Examples.s])
         (dimT dim [Examples.n; radj Examples.n; Examples.s;
                    ladj Examples.n; Examples.n])
         (F dim Examples.tv_red_alt) (F dim Examples.tv_red).
Proof.
  intros dim.
  refine (conj _ (conj _ _)).
  - exact (proj2 (proj2 (F_deq _ dim _ _ _ _ _ _ Examples.deq_tv_subj))).
  - exact (proj2 (proj2 (F_deq _ dim _ _ _ _ _ _ Examples.deq_tv_obj))).
  - exact (proj2 (proj2 (F_deq _ dim _ _ _ _ _ _ Examples.deq_tv_alt))).
Qed.


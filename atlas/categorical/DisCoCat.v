(* D14.  The Sigma of CSC10 eqs (4)-(5), by primitive recursion on the
   bound (pitfall 5). *)
Fixpoint qsum (n : nat) (f : nat -> Q) : Q :=
  match n with O => 0 | S m => qsum m f + f m end.

(* D15.  Matrices with PHANTOM dimensions (ARTIFACT-ii): the dims live
   in mat_eq and in the explicit mmul/kron arguments, which is what
   makes the monoidal structure strict on the nose. *)
Definition mat (m n : nat) : Type := nat -> nat -> Q.
Definition mat_eq (m n : nat) (A B : nat -> nat -> Q) : Prop :=
  forall i j, (i < m)%nat -> (j < n)%nat -> A i j == B i j.
Definition idm : nat -> nat -> Q :=
  fun i j => if Nat.eqb i j then 1 else 0.
Definition mmul (k : nat) (A B : nat -> nat -> Q) : nat -> nat -> Q :=
  fun i j => qsum k (fun l => A i l * B l j).
(* Row-major Kronecker; m2/n2 are the FULL row/col dims of the right
   factor (pitfall 3). *)
Definition kron (m2 n2 : nat) (A B : nat -> nat -> Q) : nat -> nat -> Q :=
  fun i j => A (i / m2)%nat (j / n2)%nat * B (i mod m2)%nat (j mod n2)%nat.

(* D16.  eps/eta: entry 1 at e_i (x) e_i (CSC10 eqs (4)-(5) pp. 12-13);
   V^l = V^r = V, so both adjoint eps/eta collapse to these. *)
Definition eps (d : nat) : nat -> nat -> Q :=
  fun _ k => if Nat.eqb (k / d)%nat (k mod d)%nat then 1 else 0.
Definition eta (d : nat) : nat -> nat -> Q :=
  fun k _ => if Nat.eqb (k / d)%nat (k mod d)%nat then 1 else 0.

(* D17.  Vectors are columns (CSC10 p. 9). *)
Definition basis (d i : nat) : nat -> nat -> Q :=
  fun r _ => if Nat.eqb r i then 1 else 0.
Definition inner (d : nat) (v w : nat -> nat -> Q) : Q :=
  qsum d (fun i => v i 0%nat * w i 0%nat).
Definition vscale (c : Q) (v : nat -> nat -> Q) : nat -> nat -> Q :=
  fun i j => c * v i j.
Definition vadd (v w : nat -> nat -> Q) : nat -> nat -> Q :=
  fun i j => v i j + w i j.

(* D19.  Decision/display layer (ARTIFACT-v: mat_eq at fixed dims IS
   decidable). *)
Definition mat_eqb (m n : nat) (A B : nat -> nat -> Q) : bool :=
  forallb (fun i => forallb (fun j => Qeq_bool (A i j) (B i j))
                      (seq 0 n)) (seq 0 m).
Definition entries (d : nat) (v : nat -> nat -> Q) : list Q :=
  map (fun i => Qred (v i 0%nat)) (seq 0 d).

(* T24.  The reflection lemma. *)
Theorem mat_eqb_sound : forall m n A B,
  mat_eqb m n A B = true -> mat_eq m n A B.
Proof.
  intros m n A B H i j Hi Hj.
  unfold mat_eqb in H.
  assert (Hi' : In i (seq 0 m)) by (apply in_seq; lia).
  assert (Hj' : In j (seq 0 n)) by (apply in_seq; lia).
  pose proof (proj1 (forallb_forall _ _) H i Hi') as Hrow.
  pose proof (proj1 (forallb_forall _ _) Hrow j Hj') as Hcell.
  apply Qeq_bool_iff, Hcell.
Qed.


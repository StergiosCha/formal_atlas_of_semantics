(* D12.  Basic types (names Bn.. avoid shadowing n, s): CSC10 §2.2
   pp. 5-6; Bsig is the sigma of the negation example §4.2. *)
Inductive basic := Bn | Bs | Bj | Bsig.

Definition n  : Simple basic := (Bn, 0%Z).
Definition s  : Simple basic := (Bs, 0%Z).
Definition jj : Simple basic := (Bj, 0%Z).
Definition sg : Simple basic := (Bsig, 0%Z).

Definition tv   : Ty basic := [radj n; s; ladj n].          (* n^r s n^l *)
Definition iv   : Ty basic := [radj n; s].                  (* n^r s     *)
Definition adjt : Ty basic := [n; ladj n].                  (* n n^l     *)
Definition does : Ty basic := [radj n; s; ladj jj; sg].
Definition nott : Ty basic := [radj sg; jj; ladj jj; sg].
Definition likew : Ty basic := [radj sg; jj; ladj n].

(* D13.  Derivation terms — closed, cast-free (++ on literals converts):
   CSC10 p. 6 (step-by-step reduction), p. 14 (the parallel morphism
   eps^r_n (x) 1_s (x) eps^l_n). *)
Definition tv_red : Red [n; radj n; s; ladj n; n] [s] :=
  red_tensor (red_cup_r n) (red_tensor (red_refl [s]) (red_cup_l n)).

Definition tv_layer_subj1 : Red [n; radj n; s; ladj n; n] [s; ladj n; n] :=
  red_tensor (red_cup_r n) (red_refl [s; ladj n; n]).
Definition tv_layer2 : Red [s; ladj n; n] [s] :=
  red_tensor (red_refl [s]) (red_cup_l n).
Definition tv_red_subj : Red [n; radj n; s; ladj n; n] [s] :=
  red_trans tv_layer_subj1 tv_layer2.

Definition tv_layer_obj1 : Red [n; radj n; s; ladj n; n] [n; radj n; s] :=
  red_tensor (red_refl [n; radj n; s]) (red_cup_l n).
Definition tv_layer_obj2 : Red [n; radj n; s] [s] :=
  red_tensor (red_cup_r n) (red_refl [s]).
Definition tv_red_obj : Red [n; radj n; s; ladj n; n] [s] :=
  red_trans tv_layer_obj1 tv_layer_obj2.

Definition tv_red_alt : Red [n; radj n; s; ladj n; n] [s] :=
  red_tensor (red_tensor (red_cup_r n) (red_refl [s])) (red_cup_l n).

Definition iv_red : Red [n; radj n; s] [s] :=
  red_tensor (red_cup_r n) (red_refl [s]).

Definition adj_red : Red [n; ladj n; n] [n] :=
  red_tensor (red_refl [n]) (red_cup_l n).

(* The negative transitive sentence "John does not like Mary"
   (CSC10 §2.2 p. 6, §4.2 p. 21): two layers of contractions. *)
Definition neg_layer1 :
  Red (n :: does ++ nott ++ likew ++ [n]) [s; ladj jj; jj; ladj jj; jj] :=
  red_tensor (red_cup_r n)
    (red_tensor (red_refl [s])
      (red_tensor (red_refl [ladj jj])
        (red_tensor (red_cup_r sg)
          (red_tensor (red_refl [jj])
            (red_tensor (red_refl [ladj jj])
              (red_tensor (red_cup_r sg)
                (red_tensor (red_refl [jj]) (red_cup_l n)))))))).
Definition neg_layer2 : Red [s; ladj jj; jj; ladj jj; jj] [s] :=
  red_tensor (red_refl [s]) (red_tensor (red_cup_l jj) (red_cup_l jj)).
Definition neg_red : Red (n :: does ++ nott ++ likew ++ [n]) [s] :=
  red_trans neg_layer1 neg_layer2.

(* T10.  The sentence reductions, at the order level: CSC10 p. 6
   "n (n^r s n^l) n -> s"; L08 ch. 3 p. 5. *)
Theorem Le_tv : Le [n; radj n; s; ladj n; n] [s].
Proof. exact (inhabits tv_red). Qed.

Theorem Le_iv : Le [n; radj n; s] [s].
Proof. exact (inhabits iv_red). Qed.

Theorem Le_adj : Le [n; ladj n; n] [n].

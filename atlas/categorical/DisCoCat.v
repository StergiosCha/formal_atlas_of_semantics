Section CompoundAdjoints.

Variable B : Type.

(* D8, generalized cast-light forms (Lambek ch. 4 p. 9: the telescoping
   (xy)^l (xy) -> y^l (x^l x) y -> y^l y -> 1; PL07 (3.3)). *)
Lemma cup_l_gen : forall (p u : Ty B), Red (ladj_ty p ++ p ++ u) u.
Proof.
  induction p as [| a p' IH]; intros u.
  - exact (red_refl u).
  - refine (red_cast _ eq_refl
      (red_trans (red_subst (ladj_ty p') (p' ++ u) (red_cup_l a))
                 (IH u))).
    unfold ladj_ty; simpl map; simpl rev.
    rewrite <- app_assoc; reflexivity.
Qed.

Lemma cup_r_gen : forall (p u : Ty B), Red (p ++ radj_ty p ++ u) u.
Proof.
  induction p as [| a p' IH]; intros u.
  - exact (red_refl u).
  - refine (red_cast _ eq_refl
      (red_trans
         (red_tensor (red_refl [a]) (IH ([radj a] ++ u)))
         (red_tensor (red_cup_r a) (red_refl u)))).
    unfold radj_ty; simpl map; simpl rev.
    simpl app.
    rewrite <- app_assoc; reflexivity.
Qed.

Lemma cap_l_gen : forall p : Ty B, Red [] (p ++ ladj_ty p).
Proof.
  induction p as [| a p' IH].
  - exact (red_refl []).
  - refine (red_cast eq_refl _
      (red_trans (red_cap_l a)
         (red_subst [a] [ladj a] IH))).
    unfold ladj_ty; simpl map; simpl rev.
    simpl app.
    rewrite app_assoc; reflexivity.
Qed.

Lemma cap_r_gen : forall p : Ty B, Red [] (radj_ty p ++ p).
Proof.
  induction p as [| a p' IH].
  - exact (red_refl []).
  - refine (red_cast eq_refl _
      (red_trans IH
         (red_subst (radj_ty p') p' (red_cap_r a)))).
    unfold radj_ty; simpl map; simpl rev.
    rewrite <- app_assoc; reflexivity.
Qed.

(* T4.  The compound adjoint laws at the order level. *)
Theorem Le_cup_l_ty : forall p : Ty B, Le (ladj_ty p ++ p) [].
Proof.
  intros p; constructor.
  refine (red_cast _ eq_refl (cup_l_gen p [])).
  rewrite app_nil_r; reflexivity.
Qed.

Theorem Le_cup_r_ty : forall p : Ty B, Le (p ++ radj_ty p) [].
Proof.
  intros p; constructor.
  refine (red_cast _ eq_refl (cup_r_gen p [])).
  rewrite app_nil_r; reflexivity.
Qed.

Theorem Le_cap_l_ty : forall p : Ty B, Le [] (p ++ ladj_ty p).
Proof. intros p; exact (inhabits (cap_l_gen p)). Qed.

Theorem Le_cap_r_ty : forall p : Ty B, Le [] (radj_ty p ++ p).
Proof. intros p; exact (inhabits (cap_r_gen p)). Qed.

(* T7.  Contravariance of the adjoints (L08 ch. 27 (3) p. 75:
   y^l = y^l 1 -> y^l x x^l -> y^l y x^l -> 1 x^l). *)
Theorem Le_contra_l : forall p q : Ty B,
  Le p q -> Le (ladj_ty q) (ladj_ty p).
Proof.
  intros p q [d]; constructor.
  refine (red_trans
    (red_cast (app_nil_r (ladj_ty q)) eq_refl
       (red_tensor (red_refl (ladj_ty q)) (cap_l_gen p)))
    (red_trans
       (red_subst (ladj_ty q) (ladj_ty p) d)
       (cup_l_gen q (ladj_ty p)))).
Qed.

Theorem Le_contra_r : forall p q : Ty B,
  Le p q -> Le (radj_ty q) (radj_ty p).
Proof.
  intros p q [d]; constructor.
  refine (red_trans
    (red_tensor (cap_r_gen p) (red_refl (radj_ty q)))
    (red_trans
       (red_cast _ eq_refl (red_subst (radj_ty p) (radj_ty q) d))
       (red_cast eq_refl (app_nil_r (radj_ty p))
          (red_tensor (red_refl (radj_ty p))
             (red_cast _ eq_refl (cup_r_gen q [])))))).
  - rewrite app_assoc; reflexivity.
  - rewrite app_nil_r; reflexivity.
Qed.

(* T8.  Adjoints are unique up to mutual reduction (L08 (14), ch. 27
   (1); CSC10 p. 5). *)
Theorem adjoint_unique_l : forall (y p : Ty B),
  Le (y ++ p) [] -> Le [] (p ++ y) ->
  Le y (ladj_ty p) /\ Le (ladj_ty p) y.
Proof.
  intros y p [d1] [d2]; split; constructor.
  - refine (red_trans
      (red_cast (app_nil_r y) eq_refl
         (red_tensor (red_refl y) (cap_l_gen p)))
      (red_cast _ eq_refl
         (red_tensor d1 (red_refl (ladj_ty p))))).
    rewrite app_assoc; reflexivity.
  - refine (red_trans
      (red_cast (app_nil_r (ladj_ty p)) eq_refl
         (red_tensor (red_refl (ladj_ty p)) d2))
      (red_cast _ eq_refl
         (red_tensor
            (red_cast (f_equal (app (ladj_ty p)) (app_nil_r p)) eq_refl
               (cup_l_gen p []))
            (red_refl y)))).
    symmetry; apply app_assoc.
Qed.

End CompoundAdjoints.

